#!/usr/bin/env python3
"""Generate/check namespaced modules from the byte-bound public proof archive.

Imports and theorem bodies are preserved verbatim. Only a namespace and
provenance comment are added; archived sources and challenges are never edited.
This binding check is not a compiler or permitted-axiom check.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
from replay_results import load_catalog

FOUNDATIONS = (
    "archetype_chi_ge_omega",
    "archetype_brooks_standard",
    "archetype_spectral_wilf",
    "mcclelland_graph_energy_upper",
    "cvetkovic_signless_laplacian_max_deg",
    "chung_normalized_laplacian_gap_upper",
    "parity_code_unique_neighbor_distance",
    "parity_code_dimension_le_order",
)
MANIFEST = "certified_lean/MathFoundry/manifest.json"


def wrap_source(source: str, name: str, source_path: str, digest: str) -> str:
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name):
        raise ValueError("Expected a sanitized Lean theorem name")
    lines = source.splitlines(keepends=True)
    imports = [i for i, line in enumerate(lines) if line.startswith("import ")]
    if not imports:
        raise ValueError("Missing import prefix")
    split = imports[-1] + 1
    prefix, body = "".join(lines[:split]), "".join(lines[split:])
    if any(line.strip() and not line.startswith("import ") for line in lines[:split]):
        raise ValueError("Unexpected command before the final import")
    # This archive contains only theorems and a scoped notation opening. Reject
    # future namespace-sensitive commands rather than silently adapting them.
    for line in body.splitlines():
        if re.match(
            r"^(?:namespace|end|section|axiom|def|abbrev|instance|opaque|structure|class|"
            r"noncomputable|private|protected|public|attribute|notation|macro|syntax|"
            r"initialize|set_option|export|import|module|prelude)\b|^#", line.lstrip()
        ):
            raise ValueError("Namespace-sensitive command in archived body")
        if line and not line[0].isspace() and not (
            line.startswith("theorem ") or line == "open scoped BigOperators"
        ):
            raise ValueError("Unsupported top-level command in archived body")
    if "_root_." in body or not body.endswith("\n"):
        raise ValueError("Root-qualified declaration or missing terminal newline")
    namespace = "MathFoundry.Archive." + name
    return (
        "-- SPDX-License-Identifier: Apache-2.0\n"
        "-- Generated by scripts/package_lean_library.py; do not edit.\n"
        f"-- Archived source: {source_path}\n-- Source SHA-256: {digest}\n"
        + prefix + f"\nnamespace {namespace}\n" + body
        + f"\nend {namespace}\n"
    )


def expected_files(root: Path = ROOT) -> dict[str, str]:
    catalog = root / "results/catalog.json"
    records, catalog_digest = load_catalog(catalog, root)
    files, packaged = {}, []
    by_id = {r["id"]: r for r in records}
    for record in records:
        name = record["theorem_name"]
        module = "MathFoundry.Archive." + name
        module_path = "certified_lean/" + module.replace(".", "/") + ".lean"
        contents = wrap_source(
            (root / record["source_path"]).read_text(), name,
            record["source_path"], record["source_sha256"],
        )
        files[module_path] = contents
        packaged.append({
            "id": record["id"], "module": module, "theorem_name": name,
            "qualified_theorem": module + "." + name,
            "source_path": record["source_path"],
            "source_sha256": record["source_sha256"],
            "challenge_sha256": record["challenge_sha256"],
            "module_path": module_path,
            "module_sha256": hashlib.sha256(contents.encode()).hexdigest(),
        })
    exports = []
    foundation_lines = ["-- SPDX-License-Identifier: Apache-2.0"]
    for identifier in FOUNDATIONS:
        name = by_id[identifier]["theorem_name"]
        module = "MathFoundry.Archive." + name
        foundation_lines.append("import " + module)
        exports.append({"id": identifier, "qualified_theorem": "MathFoundry." + name,
                        "archive_theorem": module + "." + name})
    foundation_lines += ["", "namespace MathFoundry", ""]
    for export in exports:
        module, name = export["archive_theorem"].rsplit(".", 1)
        foundation_lines.append(f"export {module} ({name})")
    foundation_lines += ["", "end MathFoundry", ""]
    files["certified_lean/MathFoundry/Foundations.lean"] = "\n".join(foundation_lines)
    files["certified_lean/MathFoundry.lean"] = (
        "-- SPDX-License-Identifier: Apache-2.0\n"
        f"-- All {len(packaged)} archived targets; original premises and bodies are preserved.\n"
        "import MathFoundry.Foundations\n"
        + "".join("import " + r["module"] + "\n" for r in packaged)
    )
    files[MANIFEST] = json.dumps({
        "schema_version": 1, "catalog_path": "results/catalog.json",
        "catalog_sha256": catalog_digest, "artifact_count": len(packaged),
        "foundation_exports": exports, "records": packaged,
    }, indent=2) + "\n"
    return files


def output_path(root: Path, relative: str) -> Path:
    base = root.resolve()
    part = Path(relative)
    if part.is_absolute() or ".." in part.parts:
        raise ValueError("Expected a repository-relative output path")
    p = base
    for component in part.parts:
        p = p / component
        if p.is_symlink():
            raise ValueError("Refusing a symlinked output component: " + relative)
    if not p.resolve().is_relative_to(base):
        raise ValueError("Output escapes the repository: " + relative)
    return p


def check(root: Path = ROOT) -> int:
    expected = expected_files(root)
    base = root.resolve()
    subtree = output_path(root, "certified_lean/MathFoundry")
    for p in subtree.rglob("*"):
        output_path(root, str(p.relative_to(base)))
    actual = {str(p.relative_to(base)) for p in subtree.rglob("*.lean")}
    desired = {p for p in expected if p.startswith("certified_lean/MathFoundry/")
               and p.endswith(".lean")}
    if actual != desired:
        raise ValueError("Archive module coverage differs from the complete catalog")
    for path, text in expected.items():
        p = output_path(root, path)
        if not p.is_file() or p.read_bytes() != text.encode():
            raise ValueError("Missing or changed generated library file: " + path)
    return sum("/Archive/" in p for p in desired)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check exact generated bytes only")
    args = parser.parse_args()
    if not args.check:
        for path, text in expected_files().items():
            p = output_path(ROOT, path)
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text)
    count = check()
    print(f"Library bindings passed: {count} targets; no compiler or AI requests")


if __name__ == "__main__":
    main()
